import streamlit as st
import requests
import pandas as pd
import numpy as np
import plotly.express as px
import os

st.set_page_config(page_title="RAG Evaluation Dashboard", layout="wide")

BASE_URL = os.getenv("BACKEND_URL", "http://localhost:8000")

st.sidebar.title("Configuration")
eval_framework = st.sidebar.radio("Evaluation Framework", ["RAGAS", "DeepEval"])

# Define the base evaluation route based on framework
if eval_framework == "RAGAS":
    eval_route = f"{BASE_URL}/evaluate"
else:
    eval_route = f"{BASE_URL}/evaluate/deepeval"

st.sidebar.divider()
st.sidebar.title("Dataset Management")
with st.sidebar.expander("📁 Generate New Dataset", expanded=False):
    uploaded_file = st.file_uploader("Upload PDF Document", type=["pdf"])
    num_questions = st.number_input(
        "Number of questions", min_value=1, max_value=50, value=10
    )

    if st.button("Generate Dataset"):
        if uploaded_file is not None:
            with st.spinner("Generating dataset... (This may take a while)"):
                try:
                    files = {
                        "file": (
                            uploaded_file.name,
                            uploaded_file.getvalue(),
                            "application/pdf",
                        )
                    }
                    data = {"num_questions": num_questions}
                    resp = requests.post(
                        f"{BASE_URL}/dataset/generate", files=files, data=data
                    )

                    if resp.status_code == 200:
                        result = resp.json()
                        st.success(
                            f"Dataset generated successfully!\nID: {result.get('dataset_id')}"
                        )
                    else:
                        st.error(f"Error: {resp.status_code} - {resp.text}")
                except Exception as e:
                    st.error(f"Failed to connect to backend: {e}")
        else:
            st.warning("Please upload a PDF file first.")


def fetch_datasets():
    try:
        resp = requests.get(f"{BASE_URL}/dataset/list")
        if resp.status_code == 200:
            return resp.json().get("datasets", [])
    except Exception as e:
        st.sidebar.error(f"Failed to load datasets: {e}")
    return []


def get_recommendations(scores):
    """Provide actionable recommendations based on metric scores."""
    recs = []
    threshold = 0.7

    if scores.get("faithfulness", 1.0) < threshold:
        recs.append(
            "🚨 **Low Faithfulness (Hallucination Detected):** The LLM is generating information not found in the context. \n*Fix:* Lower the LLM temperature and update the system prompt to strictly enforce 'Answer only using the provided context.'"
        )

    if scores.get("answer_relevancy", 1.0) < threshold:
        recs.append(
            "📉 **Low Answer Relevancy:** The answer doesn't directly address the user's question. \n*Fix:* Check if the query is ambiguous, or refine the generation prompt to be more direct."
        )

    if scores.get("context_precision", 1.0) < threshold:
        recs.append(
            "🎯 **Low Context Precision:** The retrieval fetched irrelevant contexts first. \n*Fix:* Implement a re-ranker (e.g., Cohere or Cross-Encoder) or improve your embedding model."
        )

    if scores.get("context_recall", 1.0) < threshold:
        recs.append(
            "🔍 **Low Context Recall:** The retrieval missed the actual answer completely. \n*Fix:* Increase 'Top-K' retrieval limit, adjust document chunking overlap, or consider hybrid search (Vector + BM25)."
        )

    if (
        scores.get("answer_similarity", 1.0) < threshold
        or scores.get("answer_correctness", 1.0) < threshold
    ):
        recs.append(
            "⚖️ **Low Answer Correctness/Similarity:** The generated answer strays from the ground truth. \n*Fix:* Review the ground truth data for accuracy, or switch to a more capable LLM for generation."
        )

    if not recs:
        recs.append(
            "✅ **Excellent Performance!** All metrics are looking good. Your RAG pipeline handled this query well."
        )

    return recs


def get_mock_history_data():
    """Generate mock historical data for demonstration of the analytics dashboard."""
    import random

    data = []
    for i in range(150):
        data.append(
            {
                "question": f"Sample Query {i}?",
                "answer": "This is a simulated response generated by the RAG pipeline.",
                "faithfulness": random.uniform(0.4, 1.0)
                if random.random() > 0.2
                else random.uniform(0.1, 0.5),
                "answer_relevancy": random.uniform(0.5, 1.0),
                "context_precision": random.uniform(0.3, 1.0),
                "context_recall": random.uniform(0.4, 1.0),
                "generator_llm": random.choice(
                    ["gemma4:31b-cloud", "gpt-4o", "llama-3"]
                ),
                "embedding_model": random.choice(
                    ["nomic-embed-text", "ext-embedding-3-small"]
                ),
                "chunk_size": random.choice([250, 500, 1000]),
            }
        )
    return pd.DataFrame(data)


# st.title("📊 RAG Evaluation Dashboard")
st.title("AI-Gurukul RAG Evaluation Dashboard")
st.markdown(
    "Diagnose, evaluate, and fix the performance of Retrieval-Augmented Generation pipeline."
)

tab1, tab2, tab3 = st.tabs(
    [
        "🎯 Single Query Evaluation against Ground Truth",
        "⚡ Reference-Free Evaluation (no-ground truth needed)",
        "📈 System Diagnostics & Analytics",
    ]
)

# TAB 1: Ground Truth Evaluation
with tab1:
    st.subheader("Evaluate with Ground Truth")
    datasets = fetch_datasets()
    dataset_options = {d["name"]: d["dataset_id"] for d in datasets}

    if not dataset_options:
        st.warning("No datasets found. Generate a dataset from the backend first.")
        selected_dataset_id = ""
    else:
        selected_name = st.selectbox("Select Dataset", list(dataset_options.keys()))
        selected_dataset_id = dataset_options[selected_name]

    q1 = st.text_input("Question", key="q1")
    a1 = st.text_area("Generated Answer", key="a1")
    c1 = st.text_area(
        "Retrieved Contexts (Separate distinct passages with newlines)", key="c1"
    )

    if st.button("Run Evaluation", key="btn1"):
        if not selected_dataset_id or not q1 or not a1:
            st.error("Please fill in all fields (Dataset, Question, Answer).")
        else:
            with st.spinner(f"Evaluating using {eval_framework}..."):
                # Split contexts by newline instead of comma for better text handling
                contexts_list = [c.strip() for c in c1.split("\n") if c.strip()]

                payload = {
                    "dataset_id": selected_dataset_id,
                    "question": q1,
                    "answer": a1,
                    "contexts": contexts_list,
                }

                response = requests.post(f"{eval_route}/", json=payload)

                if response.status_code == 200:
                    scores = response.json()

                    st.markdown("### Metrics")
                    cols = st.columns(len(scores))
                    for i, (metric, val) in enumerate(scores.items()):
                        cols[i].metric(
                            label=metric.replace("_", " ").title(), value=f"{val:.2f}"
                        )

                    st.markdown("### Insights & Recommendations")
                    recs = get_recommendations(scores)
                    for rec in recs:
                        st.info(rec)
                else:
                    st.error(f"Error {response.status_code}: {response.text}")

# TAB 3: System Diagnostics & Analytics
with tab3:
    # st.header("🧠 System Diagnostics & Analytics")
    st.header("System Diagnostics & Analytics")
    st.markdown(
        "Analyze historical evaluation data to find bottlenecks and actionable tweaks."
    )

    # For production, replace this with a requests.get() to your MongoDB history API
    use_mock = st.toggle("Use Mock Historical Data (For Demo)", value=False)

    if use_mock:
        df = get_mock_history_data()
    else:
        try:
            response = requests.get(f"{BASE_URL}/evaluate/history")
            if response.status_code == 200:
                data = response.json()
                # Flatten the nested 'scores' dictionary so metrics become top-level DataFrame columns
                for row in data:
                    if "scores" in row and isinstance(row["scores"], dict):
                        row.update(row.pop("scores"))
                df = pd.DataFrame(data)
                if df.empty:
                    st.info(
                        "No historical evaluation data found in the database yet. Run an evaluation first!"
                    )
            else:
                st.error(f"Failed to fetch history: {response.text}")
                df = pd.DataFrame()
        except Exception as e:
            st.error(f"Error connecting to backend history endpoint: {e}")
            df = pd.DataFrame()

    metrics = [
        "faithfulness",
        "answer_relevancy",
        "context_precision",
        "context_recall",
    ]
    available_metrics = [m for m in metrics if m in df.columns] if not df.empty else []

    if not df.empty and not available_metrics:
        st.warning(
            "No standard metrics found in historical data. Please run an evaluation."
        )

    if not df.empty and available_metrics:
        # 1. GLOBAL HEALTH OVERVIEW
        st.subheader("🔹 Global Health Overview")
        cols = st.columns(len(available_metrics))
        threshold = 0.7

        for i, m in enumerate(available_metrics):
            avg_val = df[m].mean()
            fail_pct = (df[m] < threshold).mean() * 100
            cols[i].metric(
                label=m.replace("_", " ").title(),
                value=f"{avg_val:.2f}",
                delta=f"{fail_pct:.1f}% Critical (<0.7)",
                delta_color="inverse",
            )

        st.divider()

        # 2. METRIC DISTRIBUTIONS & CORRELATIONS
        col1, col2 = st.columns(2)

        with col1:
            st.subheader("🔹 Metric Distributions")
            selected_metric = st.selectbox(
                "Select Metric for Distribution", available_metrics
            )
            fig_hist = px.histogram(
                df,
                x=selected_metric,
                nbins=20,
                color_discrete_sequence=["#636EFA"],
                title=f"{selected_metric.replace('_', ' ').title()} Distribution",
            )
            fig_hist.add_vline(
                x=threshold,
                line_dash="dash",
                line_color="red",
                annotation_text="Threshold",
            )
            st.plotly_chart(fig_hist, width="stretch")

        with col2:
            st.subheader("🔹 Correlation Matrix")
            if len(available_metrics) > 1:
                corr = df.filter(items=available_metrics).corr()
                fig_corr = px.imshow(
                    corr,
                    text_auto=".2f",
                    aspect="auto",
                    color_continuous_scale="RdBu_r",
                    title="Metric Correlations (Find Root Causes)",
                )
                st.plotly_chart(fig_corr, width="stretch")

        st.divider()

        # 3. FAILURE SEGMENTATION
        st.subheader("🔹 Failure Segmentation")
        st.markdown(
            "Identify which configuration is causing the most pipeline degradation."
        )
        segment_col = st.selectbox(
            "Segment by Configuration",
            ["generator_llm", "embedding_model", "chunk_size"],
        )

        if segment_col in df.columns:
            seg_df = df.groupby(segment_col)[available_metrics].mean().reset_index()
            fig_bar = px.bar(
                seg_df,
                x=segment_col,
                y=available_metrics,
                barmode="group",
                title=f"Average Metrics by {segment_col.replace('_', ' ').title()}",
            )
            st.plotly_chart(fig_bar, width="stretch")

        st.divider()

        # 4. ACTIONABLE TWEAKS
        st.subheader("🛠️ Recommended System Tweaks")
        worst_metric = min(available_metrics, key=lambda m: df[m].mean())
        worst_score = df[worst_metric].mean()

        if worst_score < threshold:
            st.error(
                f"**Critical Bottleneck Detected:** {worst_metric.replace('_', ' ').title()} (Avg: {worst_score:.2f})"
            )

            with st.spinner("Fetching AI recommendations..."):
                try:
                    payload = {
                        "worst_metric": worst_metric,
                        "worst_score": float(worst_score),
                        "threshold": threshold,
                    }
                    rec_response = requests.post(
                        f"{BASE_URL}/evaluate/recommendations", json=payload
                    )

                    if rec_response.status_code == 200:
                        rec_data = rec_response.json()
                        if "error" in rec_data:
                            st.error(
                                f"Failed to fetch recommendations: {rec_data['error']}"
                            )
                        else:
                            st.write(rec_data.get("recommendation", ""))
                    else:
                        st.error(
                            f"Backend error: {rec_response.status_code} - {rec_response.text}"
                        )
                except Exception as e:
                    st.error(f"Error connecting to backend: {e}")
        else:
            st.success(
                "All system average metrics are above the healthy threshold (0.7). Keep monitoring!"
            )

        st.divider()

        # 5. SAMPLE-LEVEL DRILLDOWN
        st.subheader("🔍 Sample-Level Drilldown (Worst Performers)")
        sort_metric = st.selectbox(
            "Sort failures by lowest:", available_metrics, index=0
        )
        drilldown_df = df.sort_values(by=sort_metric, ascending=True).head(15)

        # Style the dataframe to highlight failing scores in red
        def highlight_low(val):
            if isinstance(val, (int, float)) and val < threshold:
                return "color: red; font-weight: bold"
            return ""

        st.dataframe(
            drilldown_df.style.map(highlight_low, subset=available_metrics),
            width="stretch",
        )

